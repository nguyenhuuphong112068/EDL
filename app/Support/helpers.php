if (! function_exists('file_icon')) {
    /** Biểu tượng file có màu theo nhóm định dạng + đuôi file. */
    function file_icon(?string $extension, string $size = ''): string
    {
        $ext = FileType::normalize($extension);

        return '<span class="file-icon ' . e($size) . '" style="--fi:' . e(FileType::color($ext)) . '">' . e(mb_substr($ext ?: '?', 0, 4)) . '</span>';
    }
}

if (! function_exists('highlight')) {
    /** Tô sáng từ khoá tìm kiếm trong một đoạn văn bản (đã escape an toàn). */
    function highlight(?string $text, ?string $term): string
    {
        $safe = e((string) $text);
        $term = trim((string) $term);

        if ($term === '' || $safe === '') {
            return $safe;
        }

        $words = array_filter(preg_split('/\s+/u', $term), fn ($w) => mb_strlen($w) >= 2);
        if (! $words) {
            return $safe;
        }

        $pattern = '/(' . implode('|', array_map(fn ($w) => preg_quote(e($w), '/'), $words)) . ')/iu';

        return preg_replace($pattern, '<mark>$1</mark>', $safe) ?? $safe;
    }
}

if (! function_exists('query_url')) {
    /** URL hiện tại với các tham số truy vấn thay thế / bỏ (giá trị null = bỏ). */
    function query_url(array $changes): string
    {
        $query = array_merge(request()->query(), $changes);
        $query = array_filter($query, fn ($v) => $v !== null && $v !== '' && $v !== []);
        unset($query['page']);

        return request()->url() . ($query ? '?' . http_build_query($query) : '');
    }
